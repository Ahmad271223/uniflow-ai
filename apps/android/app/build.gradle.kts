// Signierung fuer den Play Store: apps/android/keystore.properties (nicht in Git) oder Umgebungsvariablen.
// Ohne Angaben wird das Release-Bundle unsigniert gebaut (Workflow); die Signatur kommt vom Inhaber.
val keystoreProps = Properties().apply {
    val f = rootProject.file("keystore.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}
fun signingValue(key: String): String? = keystoreProps.getProperty(key) ?: System.getenv("UNIFLOW_" + key.uppercase())

